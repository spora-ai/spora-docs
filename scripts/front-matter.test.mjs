// The front matter of the hand-written pages.
//
// A description is what a search result and a link preview show, and it is a
// claim about the product. A description that says something untrue is a
// public falsehood rather than a wording choice, so the social page's is
// pinned here: the plugin publishes to LinkedIn, Facebook and Instagram with
// its own OAuth, and reaches more networks through an aggregator. A copy that
// drops the aggregator again fails this test.
//
// The zernio page's is pinned for the same reason. It names the networks a
// post can target, and a count there was wrong twice — it said fifteen, and
// it named Discord, which the platform-target list in Zernio's own
// specification does not carry. A pin makes the change to that list a
// deliberate edit rather than a silent drift.
//
// The pages under docs/reference/api/ are generated by scripts/gen-api.mjs and
// carry no front matter of their own, so they are not pages here.

import { describe, it } from 'node:test'
import assert from 'node:assert/strict'
import { readFileSync, readdirSync } from 'node:fs'
import { dirname, join, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const DOCS = join(ROOT, 'docs')
const GENERATED = join(DOCS, 'reference', 'api')

function pages(dir) {
  const found = []
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name)
    if (entry.isDirectory()) {
      found.push(...pages(path))
    } else if (entry.name.endsWith('.md')) {
      found.push(path)
    }
  }
  return found
}

function frontMatter(file) {
  const raw = readFileSync(file, 'utf8')
  const match = raw.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n/)
  assert.ok(match, `${relative(ROOT, file)} carries no front matter`)
  const block = match[1]
  const title = block.match(/^title:\s*(.+)$/m)
  const description = block.match(/^description:\s*(.+)$/m)
  return {
    title: title?.[1].trim(),
    description: description?.[1].trim(),
  }
}

describe('page front matter', () => {
  it('every hand-written page carries a title and a description', () => {
    const missing = []

    for (const file of pages(DOCS)) {
      if (file.startsWith(GENERATED)) continue
      const { title, description } = frontMatter(file)
      if (!title || !description) missing.push(relative(ROOT, file))
    }

    assert.deepEqual(missing, [])
  })

  it('the social page describes the aggregator as well as the native networks', () => {
    const { description } = frontMatter(join(DOCS, 'develop/plugins/reference/social.md'))

    assert.equal(
      description,
      'Native social publishing for Spora — an agent writes and schedules your LinkedIn, Facebook and Instagram posts, and the numbers come back per network; an aggregator can add the networks Spora does not connect to natively.',
    )
  })

  it('the zernio page names the networks a post can target', () => {
    const { description } = frontMatter(join(DOCS, 'develop/plugins/reference/zernio.md'))

    assert.equal(
      description,
      'Social-media scheduling and publishing for Spora agents, powered by the Zernio API — X, Instagram, Facebook, LinkedIn, TikTok, YouTube, Pinterest, Reddit, Bluesky, Threads, Google Business Profile and Telegram.',
    )
  })
})
